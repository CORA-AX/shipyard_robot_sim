"""Static occupancy data and provenance checks, independent of ROS and Kit."""
from dataclasses import dataclass
import hashlib
import json
import math
from pathlib import Path

import yaml


@dataclass(frozen=True)
class NavigationMap:
    resolution: float
    origin: tuple
    width: int
    height: int
    data: tuple
    source: str

    @property
    def bounds(self):
        x, y = self.origin
        return x, y, x+self.width*self.resolution, y+self.height*self.resolution

    def free(self, x, y):
        if not all(math.isfinite(v) for v in (x, y)):
            return False
        col, row = (math.floor((v-o)/self.resolution) for v, o in zip((x, y), self.origin))
        return 0 <= col < self.width and 0 <= row < self.height and self.data[row*self.width+col] == 0

    def inside(self, x, y, margin=0.):
        x0, y0, x1, y1 = self.bounds
        return x0+margin <= x < x1-margin and y0+margin <= y < y1-margin

    def footprint_free(self, x, y, yaw, footprint, padding=.02):
        """Conservative rectangle/cell overlap, including unknown floor cells."""
        if not all(math.isfinite(v) for v in (x,y,yaw)):
            return False
        x0,x1 = min(p[0] for p in footprint)-padding, max(p[0] for p in footprint)+padding
        y0,y1 = min(p[1] for p in footprint)-padding, max(p[1] for p in footprint)+padding
        c,s = math.cos(yaw),math.sin(yaw)
        polygon = [(x+c*a-s*b,y+s*a+c*b) for a,b in ((x0,y0),(x1,y0),(x1,y1),(x0,y1))]
        if not all(self.inside(a,b) for a,b in polygon):
            return False
        c0,c1 = (math.floor((v-self.origin[0])/self.resolution) for v in
                 (min(p[0] for p in polygon),max(p[0] for p in polygon)))
        r0,r1 = (math.floor((v-self.origin[1])/self.resolution) for v in
                 (min(p[1] for p in polygon),max(p[1] for p in polygon)))
        axes = []
        for nx,ny in ((1.,0.),(0.,1.),(c,s),(-s,c)):
            projection = [a*nx+b*ny for a,b in polygon]
            axes.append((nx,ny,min(projection),max(projection),self.resolution/2.*(abs(nx)+abs(ny))))
        for row in range(r0,r1+1):
            for col in range(c0,c1+1):
                if self.data[row*self.width+col] == 0:
                    continue
                a,b = self.origin[0]+(col+.5)*self.resolution,self.origin[1]+(row+.5)*self.resolution
                if all(a*nx+b*ny+half >= low-1e-9 and a*nx+b*ny-half <= high+1e-9
                       for nx,ny,low,high,half in axes):
                    return False
        return True


def read_pgm(path):
    """Read the canonical P5 maps generated by Hunter (top image row first)."""
    with Path(path).open('rb') as stream:
        if stream.readline().strip() != b'P5':
            raise ValueError('Hunter maps require a binary P5 PGM image.')
        line = stream.readline()
        while line.startswith(b'#'):
            line = stream.readline()
        width, height = map(int, line.split())
        if stream.readline().strip() != b'255' or width <= 0 or height <= 0:
            raise ValueError('Invalid PGM dimensions or depth.')
        pixels = stream.read()
    if len(pixels) != width*height or set(pixels)-{0, 205, 254}:
        raise ValueError('Invalid map raster length or occupancy values.')
    return width, height, pixels


def load_map(root, profile, verify_sources=True):
    root = Path(root)
    if profile.map_file is None:
        x0, y0, x1, y1 = profile.bounds
        width, height = round((x1-x0)/profile.resolution), round((y1-y0)/profile.resolution)
        data = tuple(100 if x in (0, width-1) or y in (0, height-1) else 0
                     for y in range(height) for x in range(width))
        return NavigationMap(profile.resolution, (x0, y0), width, height, data, 'generated_empty_flat_map')
    path = profile.map_file
    if not path.is_file():
        raise ValueError('Shipyard map missing. Run: python3 hunter/scripts/export_map.py --environment shipyard')
    metadata_path = path.with_suffix('.json')
    config = yaml.safe_load(path.read_text())
    metadata = json.loads(metadata_path.read_text())
    image = path.parent/config['image']
    if hashlib.sha256(image.read_bytes()).hexdigest() != metadata['image_sha256']:
        raise ValueError('Shipyard map image changed; regenerate the map.')
    if verify_sources:
        for source in metadata['sources']:
            asset = root/source['path']
            if not asset.is_file() or hashlib.sha256(asset.read_bytes()).hexdigest() != source['sha256']:
                raise ValueError(f'Shipyard map is stale: {source["path"]}. Run python3 hunter/scripts/export_map.py --environment shipyard')
    if config['origin'][2] != 0. or config.get('negate', 0) != 0:
        raise ValueError('Only unrotated, non-negated ground-truth maps are supported.')
    width, height, pixels = read_pgm(image)
    convert = {0: 100, 205: -1, 254: 0}
    data = tuple(convert[pixels[row*width+col]] for row in reversed(range(height)) for col in range(width))
    result = NavigationMap(float(config['resolution']), tuple(config['origin'][:2]), width, height, data, str(path))
    if abs(result.resolution-profile.resolution) > 1e-9 or any(abs(a-b) > 1e-6 for a,b in zip(result.bounds, profile.bounds)):
        raise ValueError('Map and environment profile bounds/resolution disagree. Regenerate the map.')
    return result


def occupancy_message(grid, time):
    from nav_msgs.msg import OccupancyGrid
    message = OccupancyGrid()
    message.header.frame_id, message.header.stamp = 'map', time
    message.info.resolution = grid.resolution
    message.info.width, message.info.height = grid.width, grid.height
    message.info.origin.position.x, message.info.origin.position.y = grid.origin
    message.info.origin.orientation.w = 1.
    message.data = list(grid.data)
    return message
